import 'package:flutter/material.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:supabase_flutter/supabase_flutter.dart';

/// Generates a basic Tamasuk (loan agreement) PDF for a loan.
/// Legal review required before relying on this as an enforceable instrument.
Future<void> exportTamasuk(BuildContext context, String loanId) async {
  final client = Supabase.instance.client;
  final loan = await client
      .from('loans')
      .select('*, parties(name, phone, address, id_number)')
      .eq('id', loanId)
      .maybeSingle();
  if (loan == null) return;
  final party = loan['parties'] as Map? ?? {};
  final pdf = pw.Document();
  pdf.addPage(pw.Page(
    pageFormat: PdfPageFormat.a4,
    build: (_) => pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text('TAMASUK (Loan Agreement)',
            style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold)),
        pw.SizedBox(height: 12),
        pw.Text('Date: ${loan['start_date']}'),
        pw.SizedBox(height: 8),
        pw.Text('Borrower / Party: ${party['name'] ?? '-'}'),
        pw.Text('Phone: ${party['phone'] ?? '-'}'),
        pw.Text('Address: ${party['address'] ?? '-'}'),
        pw.Text('ID No: ${party['id_number'] ?? '-'}'),
        pw.SizedBox(height: 8),
        pw.Text('Principal Amount: Rs ${loan['principal_amount']}'),
        pw.Text('Interest Rate: ${(loan['rate'] as num) * 100}% per annum (${loan['rate_type']})'),
        pw.Text('Day Base: ${loan['day_base']}'),
        pw.Text('Direction: ${loan['direction']}'),
        pw.Text('Start Date: ${loan['start_date']}'),
        pw.Text('Due Date: ${loan['due_date'] ?? '-'}'),
        pw.SizedBox(height: 8),
        pw.Text('Remarks: ${loan['remarks'] ?? '-'}'),
        pw.SizedBox(height: 24),
        pw.Text('This document is generated by nHisab and is subject to review by a '
            'Nepali chartered accountant / counsel before being treated as a '
            'legally enforceable instrument.'),
      ],
    ),
  ));
  await Printing.sharePdf(
      bytes: await pdf.save(), filename: 'tamasuk_$loanId.pdf');
}
